MARKS = [
    (26.0, "паракит и лонч ди"),
    (190.0, "Мониторы — до пятницы"),
    (340.0, "Диаризация длинных файлов падает по памяти на записях дольше часа, решили сдвинуть релиз на неделю."),
    (440.0, "стажёр"),
]


def build(scale_gap: float = 13.0) -> dict:
    """Реплики идут с шагом по длине текста: ~13 символов в секунду речи плюс пауза."""
    turns = []
    clock = 3.0
    for topic in TOPICS:
        for speaker, text in topic:
            length = max(3.0, len(text) / scale_gap)
            turns.append({"speaker": speaker, "source": "mic" if speaker == ME else "system",
                          "start": round(clock, 2), "end": round(clock + length, 2), "text": text})
            clock += length + 1.2
        clock += 45.0  # переход между темами
    return {
        "date": "2026-10-11T12:00",
        "title": "Синк команды Mostik (синтетика)",
        "attendees": [],
        "marks": [{"at": at, "text": text} for at, text in MARKS],
        "duration_seconds": round(clock, 2),
        "language": "ru",
        "participants": [ME, S1, S2],
        "turns": turns,
    }


def main() -> int:
    out = Path(sys.argv[1] if len(sys.argv) > 1 else "engine/bench/out/meeting-ai/synthetic")
    out.mkdir(parents=True, exist_ok=True)
    data = build()
    (out / "transcript.json").write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    chars = sum(len(t["text"]) for t in data["turns"])
    print(f"{out}: реплик {len(data['turns'])}, символов {chars}, длительность {data['duration_seconds'] / 60:.1f} мин")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
