def build(root: Path) -> tuple[Path, Path]:
    """Собрать корпус в `root`: `meetings/<папка>/transcript.json` и `notes/<документы>`."""
    meetings = root / "meetings"
    notes = root / "notes"
    for folder, (title, turns) in MEETINGS.items():
        target = meetings / folder
        target.mkdir(parents=True, exist_ok=True)
        payload = {
            "date": f"{folder[:10]}T{folder[11:13]}:{folder[13:15]}",
            "title": title,
            "turns": [
                {"speaker": speaker, "source": "mic" if speaker == ME else "system", "start": start,
                 "end": start + 5.0, "text": text}
                for speaker, start, text in turns
            ],
        }
        (target / "transcript.json").write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    notes.mkdir(parents=True, exist_ok=True)
    for name, text in DOCS.items():
        (notes / name).write_text(text, encoding="utf-8")
    return meetings, notes


def matches(ref: str, path: str, expected: list[str]) -> bool:
    """Попадание выдачи в ожидаемое: ссылка встречи целиком или имя файла документа."""
    for item in expected:
        if "#" in item and ref.endswith(item):
            return True
        if "#" not in item and Path(path).name == item:
            return True
    return False
